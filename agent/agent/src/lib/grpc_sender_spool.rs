// ============================================================
// OLOPA — gRPC Sender + Disk Spool
// ============================================================
// Receives BatchOutput from the Batcher and ships it to the
// backend ingest gateway over a persistent mTLS HTTP/2 gRPC
// stream. One long-lived stream per agent — no reconnect per
// batch.
//
// Backpressure contract (from backend ThrottleAck):
//   throttle_ratio = 0.0  → all clear, send at full rate
//   throttle_ratio > 0.0  → raise flush interval proportionally
//   throttle_ratio > 0.8  → activate disk spool
//   throttle_ratio = 1.0  → stop sending, spool everything
//
// Disk spool:
//   Append-only log: [u32 len BE][batch bytes] per entry.
//   Written when throttle_ratio > 0.8 or stream is unavailable.
//   Replayed FIFO when the backend recovers.
//   Max spool size enforced — oldest entries evicted if exceeded.
// ============================================================

