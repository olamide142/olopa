use tonic::transport::{Channel, ClientTlsConfig, Certificate, Identity};
use tonic::{Request, Streaming};

// Proto-generated types (placeholders — replace with prost-generated)
// In production: generated by build.rs from olopa.proto
mod proto {
    #[derive(Clone, prost::Message)]
    pub struct BatchFrame {
        #[prost(bytes = "bytes", tag = "1")]
        pub payload: bytes::Bytes,
        #[prost(uint64, tag = "2")]
        pub sequence: u64,
    }

    #[derive(Clone, prost::Message)]
    pub struct IngestAck {
        #[prost(uint32, tag = "1")]
        pub accepted: u32,
        #[prost(uint32, tag = "2")]
        pub rejected: u32,
        #[prost(uint32, tag = "3")]
        pub retry_after_ms: u32,
        #[prost(uint32, tag = "4")]
        pub suggested_batch_bytes: u32,
        #[prost(float, tag = "5")]
        pub throttle_ratio: f32,
    }
}

